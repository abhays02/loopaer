"""Convert a compiled skill into portable formats: Claude Skill, Cursor rules,
OpenAI Agent, MCP tool. All are small transformations of the skill JSON.
"""
from typing import Dict, Any


def to_claude_skill(skill: Dict[str, Any]) -> Dict[str, Any]:
    """Claude Skill JSON — a system prompt + workflow + examples."""
    return {
        "kind": "claude_skill",
        "name": skill.get("name", "loopaer-skill"),
        "description": skill.get("purpose", ""),
        "version": skill.get("version", "1.0.0"),
        "system_prompt": skill.get("system_prompt", ""),
        "instructions": [
            "Follow the workflow steps in order.",
            *[f"Step {i+1}: {s}" for i, s in enumerate(skill.get("workflow", []))],
        ],
        "tools": skill.get("tool_requirements", []),
        "examples": [{
            "input": skill.get("example_input", ""),
            "output": skill.get("example_output", ""),
        }] if skill.get("example_input") else [],
        "failure_modes": skill.get("failure_modes", []),
    }


def to_cursor_rules(skill: Dict[str, Any]) -> str:
    """Cursor `.cursorrules` / `.mdc` markdown."""
    lines = [
        f"# {skill.get('name', 'Skill')}",
        "",
        skill.get("purpose", ""),
        "",
        "## System Prompt",
        "",
        skill.get("system_prompt", ""),
        "",
        "## Workflow",
        "",
    ]
    for i, s in enumerate(skill.get("workflow", []) or []):
        lines.append(f"{i+1}. {s}")
    lines += ["", "## Tools Required", ""]
    for t in skill.get("tool_requirements", []) or []:
        lines.append(f"- {t}")
    if skill.get("failure_modes"):
        lines += ["", "## Watch For", ""]
        for f in skill["failure_modes"]:
            lines.append(f"- {f}")
    lines += ["", f"_generated by Loopaer · v{skill.get('version','1.0.0')}_"]
    return "\n".join(lines)


def to_openai_agent(skill: Dict[str, Any]) -> Dict[str, Any]:
    """Minimal OpenAI Agents SDK config."""
    return {
        "kind": "openai_agent",
        "name": skill.get("name", "loopaer-agent"),
        "instructions": (
            skill.get("system_prompt", "") + "\n\nWorkflow:\n" +
            "\n".join(f"- {s}" for s in skill.get("workflow", []) or [])
        ),
        "tools": [{"type": "function", "name": t} for t in skill.get("tool_requirements", []) or []],
        "model": (skill.get("recommended_models") or ["openrouter/free"])[0],
    }


def to_mcp_skill(skill: Dict[str, Any]) -> Dict[str, Any]:
    """Model Context Protocol skill descriptor."""
    return {
        "kind": "mcp_skill",
        "schema_version": "2024-11-05",
        "name": skill.get("name", "loopaer-skill"),
        "description": skill.get("purpose", ""),
        "version": skill.get("version", "1.0.0"),
        "system": skill.get("system_prompt", ""),
        "resources": [],
        "prompts": [{
            "name": skill.get("name", "loopaer-skill"),
            "description": skill.get("purpose", ""),
            "arguments": [{"name": "input", "description": "user input", "required": True}],
        }],
        "tools": [{"name": t, "description": t} for t in skill.get("tool_requirements", []) or []],
    }


FORMATTERS = {
    "claude": to_claude_skill,
    "cursor": to_cursor_rules,
    "openai": to_openai_agent,
    "mcp": to_mcp_skill,
}
